"""
某商店出售某品牌运动鞋，每双定价160，1双不打折，2双(含)到4双(含)打九折，5双(含)到9双(含)打八折，10双(含)以上打七折，键盘输入购买数量，屏幕输出总额(保留整
数)。示例格式如下：
输入:1
输出：总额为：160
"""
n = eval(input("请输入数量："))
if n <= 1:
	cost = 160 * n
elif 2 <= n <= 4:
	cost = 160 * n * 0.9
elif 5 <= n <= 9:
	cost = 160 * n * 0.8
else:
	cost = 160 * n * 0.7
cost = round(cost)
print("金额为",cost)
